-- ============================================================
-- 照片「内容指纹」字段（用于识别重复上传，独立可执行）
-- 依赖：public.album_photos（已存在）
-- ------------------------------------------------------------
-- 作用：上传时给每张照片存一个内容哈希（SHA-256），
--       下次选择文件上传时，前端本地算出同样的哈希与该相册已有照片比对，
--       完全相同的原图文件会被标记「已上传」（不自动取消，传不传由用户决定）。
-- 说明：只对"上线本功能之后"上传的照片有指纹；历史老照片该字段为空，
--       不影响使用，只是老照片不会参与重复识别。
-- ============================================================

ALTER TABLE public.album_photos ADD COLUMN IF NOT EXISTS content_hash TEXT;

-- 按相册 + 指纹建索引，便于快速比对（同一相册内是否已存在相同文件）
CREATE INDEX IF NOT EXISTS idx_album_photos_album_hash
  ON public.album_photos(album_id, content_hash);

